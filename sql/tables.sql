CREATE TABLE COLABORADORES (
  CEDULA VARCHAR(20),
  CUPO_MENSUAL DECIMAL(12,2),
  FECHA_CREACION TIMESTAMP
);

CREATE TABLE CUPO_HISTORIAL (
  CEDULA VARCHAR(20),
  CUPO_ANTERIOR DECIMAL(12,2),
  CUPO_NUEVO DECIMAL(12,2),
  FECHA TIMESTAMP
);

CREATE TABLE MOVIMIENTOS (
  ID SERIAL,
  CEDULA VARCHAR(20),
  TIPO VARCHAR(15),        -- 'Acreditacion' | 'Gasto'
  ORIGEN VARCHAR(15),      -- 'Facturas' | 'GasClub' | null
  REFERENCIA VARCHAR(30),  -- nº de factura o código GasClub
  MONTO DECIMAL(12,2),
  ESTADO VARCHAR(15),      -- 'Pendiente' | 'Aprobado' | null
  FECHA TIMESTAMP
);